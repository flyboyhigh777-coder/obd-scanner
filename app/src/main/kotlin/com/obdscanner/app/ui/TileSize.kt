package com.obdscanner.app.ui

/**
 * Размер плитки на приборке - её ширина в колонках сетки.
 *
 * Хранится не числом колонок, а намерением: "обычная", "пошире", "во всю
 * ширину". Колонок на телефоне две, на магнитоле четыре, и телефонная
 * "во всю ширину" это две колонки, а на магнитоле - четыре. Записать в
 * настройки число значило бы, что плитка, растянутая на магнитоле, после
 * пересадки в телефон займёт ровно половину ряда - то есть не то, что просили.
 *
 * Высота у всех плиток одинаковая, и это намеренно: ряды разной высоты
 * выглядят лестницей, а взгляд на ходу должен находить цифру там же, где
 * нашёл её в прошлый раз. Крупнее плитка - крупнее цифры в ней, и это и есть
 * то, ради чего её растягивают.
 */
enum class TileSize(val code: Int) {
    /** Одна колонка - столько плиток в ряду, сколько влезает. */
    NORMAL(1),

    /** Две колонки. На телефоне это уже весь ряд. */
    WIDE(2),

    /** Весь ряд целиком, сколько бы колонок на экране ни было. */
    FULL(0);

    /** Сколько колонок займёт при такой ширине сетки. */
    fun span(columns: Int): Int = when (this) {
        NORMAL -> 1
        WIDE -> minOf(2, columns)
        FULL -> columns
    }.coerceAtLeast(1)

    companion object {
        /** Размер по записи в настройках; незнакомая запись - обычная плитка. */
        fun of(code: Int?): TileSize = entries.firstOrNull { it.code == code } ?: NORMAL

        /**
         * Что предлагать на выбор.
         *
         * На телефоне с двумя колонками "пошире" и "во всю ширину" - одно и то
         * же, и показывать обе строчки значит предлагать выбор, которого нет.
         */
        fun choices(columns: Int): List<TileSize> =
            if (columns <= 2) listOf(NORMAL, FULL) else listOf(NORMAL, WIDE, FULL)
    }
}

/**
 * Насколько крупнее цифры в растянутой плитке.
 *
 * Плитку растягивают не ради пустого места: за рулём это делают с тем
 * параметром, который хотят видеть боковым зрением. Поэтому ширина тянет за
 * собой размер цифр - но медленнее, чем растёт сама плитка, иначе в широкой
 * плитке "1234 об/мин" снова не помещается и подгонка шрифта съедает прибавку.
 */
fun tileValueScale(span: Int): Float = when {
    span <= 1 -> 1f
    span == 2 -> 1.35f
    span == 3 -> 1.6f
    else -> 1.8f
}
