package com.obdscanner.core.pro

/**
 * Что в приложении платное.
 *
 * Перечисление - и есть вся граница между бесплатной версией и Pro: чего в
 * этом списке нет, то бесплатно. Нигде больше решения «это за деньги» не
 * принимается, и чтобы перенести функцию из платных в бесплатные, достаточно
 * убрать строчку отсюда.
 *
 * Список собран по одному принципу: платить человек должен за то, что
 * приложение **посчитало или собрало** за него, а не за доступ к собственной
 * машине. Прочитать и погасить ошибку, узнать, что она значит, посмотреть
 * готовность тестов перед ТО, следить за температурой на ходу - это то, ради
 * чего покупался адаптер, и это бесплатно навсегда.
 *
 * Чего здесь намеренно нет и не будет:
 *
 * - **частота опроса**. Искусственно замедлить приборы и продавать скорость -
 *   самый ненавидимый вид платной стены: человек видит дёргающиеся стрелки и
 *   пишет, что его специально тормозят. Продаётся количество плиток, а не их
 *   частота обновления;
 * - **расшифровка кодов**. Показывать «P0420» и просить денег за смысл -
 *   классика злых отзывов;
 * - **сброс ошибок**. Причина установки номер один;
 * - **режим 06 и лямбда-зонды**. Самая трудоёмкая часть приложения, и всё же
 *   бесплатная: человек, который дошёл до режима 06 и увидел, что катализатор
 *   на пределе ещё до лампы, - это лучшая реклама, какая у приложения есть.
 */
enum class ProFeature {

    /** Полная проверка одной кнопкой и отчёт: PDF, текст, «поделиться». */
    REPORT,

    /** Поиск блоков вне OBD-II: ABS, подушки, АКПП, ЭУР. */
    MODULE_SCAN,

    /** Свои параметры: формулы, перебор режима 22, снимок «до и после». */
    CUSTOM_PIDS,

    /** Запись поездки: пробег, расход, средняя скорость, выгрузка CSV. */
    TRIP,

    /** Замеры разгона и торможения, оценка мощности и момента. */
    PERFORMANCE,

    /** Счётчики наработки бортовых тестов (IPT, режим 09). */
    COUNTERS,

    /** Тест пуска, график напряжения, калькулятор утечки. */
    BATTERY_TESTS,

    /** Приборка без ограничения на число плиток и с их перестановкой. */
    DASHBOARD_FULL,

    /** Архив прочитанных ошибок глубже последней записи. */
    DTC_ARCHIVE
}
