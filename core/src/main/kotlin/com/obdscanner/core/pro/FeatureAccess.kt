package com.obdscanner.core.pro

/**
 * Что сейчас доступно: единственный ответчик на вопрос «можно ли».
 *
 * Отделено от того, **откуда** взялось «куплено»: магазин, ключ, тестовый
 * режим разработчика - это дело приложения и оно меняется вместе со страной
 * и магазином, а правила доступа одни и те же везде. Поэтому правила живут в
 * :core, проверяются обычными тестами и не знают ни про Google Play, ни про
 * Android вообще.
 */
data class FeatureAccess(val pro: Boolean) {

    /** Доступна ли платная возможность. */
    fun allows(feature: ProFeature): Boolean = pro

    /**
     * Сколько плиток можно держать на приборке.
     *
     * Ограничение именно здесь, а не в экране: иначе оно разъедется с тем,
     * что показано в объяснении «что даёт Pro».
     */
    val dashboardTileLimit: Int
        get() = if (pro) UNLIMITED_TILES else ProPolicy.FREE_TILE_LIMIT

    /**
     * Влезет ли ещё одна плитка.
     *
     * [current] - сколько выбрано сейчас. Считаются все выбранные параметры,
     * включая те, что вынесены в большие шкалы: человек видит их на экране и
     * считает плитками, а объяснять ему разницу - значит спорить с тем, что он
     * видит.
     */
    fun canAddTile(current: Int): Boolean = current < dashboardTileLimit

    companion object {
        /** Всё открыто - так выглядит доступ, когда Pro есть. */
        val PRO = FeatureAccess(pro = true)

        /** Бесплатная версия. */
        val FREE = FeatureAccess(pro = false)

        /** Предел, означающий «без ограничения». */
        const val UNLIMITED_TILES = Int.MAX_VALUE
    }
}

/** Числа, которые решают, где именно проходит граница. */
object ProPolicy {

    /**
     * Сколько плиток показывает бесплатная версия.
     *
     * Шесть - потому что меньше четырёх приборка перестаёт быть приборкой
     * (температура, нагрузка, дроссель, напряжение - это уже четыре), а шесть
     * закрывают обычный набор и оставляют видимый смысл снимать ограничение.
     * Выбирать эти шесть можно из всех девяноста трёх параметров: урезан
     * размер приборки, а не список того, что машина умеет показать.
     */
    const val FREE_TILE_LIMIT = 6
}
